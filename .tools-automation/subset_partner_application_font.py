from __future__ import annotations

import base64
import json
from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".tools-automation" / "LongZhuTi-Regular.ttf"
TARGET = ROOT / "frontend" / "pages" / "partner" / "assets" / "fonts"
CHARACTERS = "申请入驻"

TARGET.mkdir(parents=True, exist_ok=True)
options = subset.Options()
options.flavor = "woff"
options.layout_features = ["kern", "liga", "clig", "calt", "locl", "ccmp"]
options.name_IDs = ["*"]
options.name_legacy = True
options.name_languages = ["*"]
font = subset.load_font(str(SOURCE), options)
subsetter = subset.Subsetter(options=options)
subsetter.populate(text=CHARACTERS)
subsetter.subset(font)
output = TARGET / "application-display-subset.woff"
subset.save_font(font, str(output), options)
encoded = base64.b64encode(output.read_bytes()).decode("ascii")
(TARGET / "application-display-font.ts").write_text(
    "// Generated by .tools-automation/subset_partner_application_font.py.\n"
    "// Source font: Long Zhu Ti (SIL Open Font License 1.1).\n"
    f"export const APPLICATION_DISPLAY_CHARACTERS = {json.dumps(CHARACTERS, ensure_ascii=False)};\n"
    f"export const APPLICATION_DISPLAY_FONT_SOURCE = 'data:font/woff;base64,{encoded}';\n",
    encoding="utf-8",
)
print(f"application display: {len(CHARACTERS)} characters; {output.stat().st_size} bytes WOFF")
