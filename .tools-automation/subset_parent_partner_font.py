from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
SOURCE = ROOT / ".tools-automation/ZCOOLKuaiLe-Regular.ttf"
LICENSE = ROOT / ".tools-automation/ZCOOLKuaiLe-OFL.txt"
SOURCE_HASH = "812a6fc1fe54b6d73a419245c32dfeba8aa33104d5be90d1cf6af082007cb71d"
ASCII = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 %+-:.,/()[]￥¥·—…"
PUNCTUATION = "，。！？、；：‘’“”《》【】（）"


def collect_characters(role: str) -> str:
    sources = list((FRONTEND / "pages" / role).rglob("*.wxml"))
    sources.extend((FRONTEND / "pages" / role).rglob("*.ts"))
    for directory in ("components", "services", "data", "types", "utils"):
        sources.extend(
            path for path in (FRONTEND / directory).rglob("*")
            if path.suffix in (".ts", ".wxml") and path.name.startswith(role + "-")
        )
    sources.extend((ROOT / "docs/verification/fixtures").glob(role + "-*.json"))
    sources.extend((FRONTEND / "mock/fixtures").glob(role + "*.ts"))
    sources.append(ROOT / "backend/prisma/seed.ts")
    characters = set(ASCII)
    for source in sources:
        if "fonts" in source.parts or "node_modules" in source.parts:
            continue
        for char in source.read_text(encoding="utf-8"):
            if "\u3400" <= char <= "\u9fff" or char in PUNCTUATION:
                characters.add(char)
    return "".join(sorted(characters))


def verify_cmap(font: TTFont, characters: str) -> None:
    missing = sorted({ord(char) for char in characters} - set(font.getBestCmap()))
    if missing:
        raise ValueError(f"Missing glyphs: {missing}")


def build(role: str, check_only: bool) -> dict:
    characters = collect_characters(role)
    directory = FRONTEND / "pages" / role / "assets/fonts"
    target = directory / "pdf-display-subset.woff"
    if check_only:
        font = TTFont(target)
        verify_cmap(font, characters)
        if target.stat().st_size > 128 * 1024:
            raise ValueError(f"{role}: font budget exceeded")
        if (directory / "pdf-OFL.txt").read_text(encoding="utf-8") != LICENSE.read_text(encoding="utf-8"):
            raise ValueError(f"{role}: license does not match")
        return {"role": role, "characters": len(characters), "bytes": target.stat().st_size, "missing": 0}

    options = subset.Options()
    options.flavor = "woff"
    options.layout_features = ["kern", "liga", "clig", "calt", "locl", "ccmp"]
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    font = subset.load_font(str(SOURCE), options)
    verify_cmap(font, characters)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(text=characters)
    subsetter.subset(font)
    verify_cmap(font, characters)
    stream = io.BytesIO()
    subset.save_font(font, stream, options)
    data = stream.getvalue()
    if len(data) > 128 * 1024:
        raise ValueError(f"{role}: font budget exceeded ({len(data)} bytes)")
    encoded = base64.b64encode(data).decode("ascii")
    prefix = role.upper().replace("-", "_") + "_PDF_DISPLAY_FONT"
    generated = (
        "// Generated by .tools-automation/subset_parent_partner_font.py.\n"
        "// Source font: ZCOOL KuaiLe (SIL Open Font License 1.1).\n"
        f"export const {prefix}_CHARACTERS =\n"
        f"  {json.dumps(characters, ensure_ascii=False)};\n"
        f"export const {prefix}_SOURCE =\n"
        f"  'data:font/woff;base64,{encoded}';\n"
    )
    directory.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)
    (directory / "pdf-display-font.ts").write_text(generated, encoding="utf-8")
    (directory / "pdf-OFL.txt").write_text(LICENSE.read_text(encoding="utf-8"), encoding="utf-8")
    return {"role": role, "characters": len(characters), "bytes": len(data), "missing": 0}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--role", choices=("parent", "partner", "teacher", "campus-manager", "operator")
    )
    args = parser.parse_args()
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != SOURCE_HASH:
        raise ValueError("Source fingerprint changed; recheck provenance before generating")
    license_text = LICENSE.read_text(encoding="utf-8")
    if "Copyright 2018 The ZCOOL KuaiLe Project Authors" not in license_text:
        raise ValueError("Source copyright missing")
    if "SIL OPEN FONT LICENSE Version 1.1" not in license_text:
        raise ValueError("Complete OFL record required")
    roles = (args.role,) if args.role else ("parent", "partner")
    print(json.dumps([build(role, args.check) for role in roles], indent=2))


if __name__ == "__main__":
    main()
