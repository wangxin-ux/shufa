from __future__ import annotations

import base64
import json
from pathlib import Path

from fontTools import subset


ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
SOURCE_FONT = ROOT / ".tools-automation" / "LongZhuTi-Regular.ttf"
OUTPUT_DIR = FRONTEND / "assets" / "fonts"
OUTPUT_FONT = OUTPUT_DIR / "parent-display-subset.woff"
OUTPUT_SOURCE = OUTPUT_DIR / "parent-display-font.ts"

ASCII = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 %+-:.,/()[]￥¥·—…"


def collect_characters() -> str:
    characters = set(ASCII)
    sources = []
    for extension in ("*.wxml", "*.ts"):
        for path in FRONTEND.rglob(extension):
            if "node_modules" in path.parts or path == OUTPUT_SOURCE:
                continue
            sources.append(path)
    sources.append(ROOT / "backend" / "prisma" / "seed.ts")
    sources.extend((ROOT / "docs" / "verification" / "fixtures").glob("parent-*.json"))
    for path in sources:
        for char in path.read_text(encoding="utf-8"):
            if "\u3400" <= char <= "\u9fff" or char in "，。！？、；：‘’“”《》【】（）":
                characters.add(char)
    return "".join(sorted(characters))


def build_subset(characters: str) -> None:
    options = subset.Options()
    options.flavor = "woff"
    options.layout_features = ["kern", "liga", "clig", "calt", "locl", "ccmp"]
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    font = subset.load_font(str(SOURCE_FONT), options)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(text=characters)
    subsetter.subset(font)
    subset.save_font(font, str(OUTPUT_FONT), options)


def write_typescript_source(characters: str) -> None:
    encoded = base64.b64encode(OUTPUT_FONT.read_bytes()).decode("ascii")
    OUTPUT_SOURCE.write_text(
        "// Generated by .tools-automation/subset_parent_font.py.\n"
        "// Source font: Long Zhu Ti (SIL Open Font License 1.1).\n"
        "export const PARENT_DISPLAY_FONT_CHARACTERS =\n"
        f"  {json.dumps(characters, ensure_ascii=False)};\n"
        "export const PARENT_DISPLAY_FONT_SOURCE =\n"
        f"  'data:font/woff;base64,{encoded}';\n",
        encoding="utf-8",
    )


OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
characters = collect_characters()
build_subset(characters)
write_typescript_source(characters)
print(f"glyph corpus: {len(characters)} characters")
print(f"font: {OUTPUT_FONT.stat().st_size / 1024:.1f} KB")
print(f"typescript: {OUTPUT_SOURCE.stat().st_size / 1024:.1f} KB")
